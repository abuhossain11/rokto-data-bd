export function getDivisionById(id: string): Division | undefined {
  return DIVISIONS.find((d) => d.id === id);
}

export function getDistrictById(id: string): District | undefined {
  return DISTRICTS.find((d) => d.id === id);
}

export function getDistrictsByDivision(divisionId: string): District[] {
  return DISTRICTS.filter((d) => d.divisionId === divisionId);
}

export function getUpazilasByDistrict(districtId: string) {
  const district = getDistrictById(districtId);
  return district ? district.upazilas : [];
}

export function getLocationName(
  divisionId: string,
  districtId: string,
  upazilaId?: string,
  lang: 'bn' | 'en' = 'bn'
): string {
  const div = getDivisionById(divisionId);
  const dist = getDistrictById(districtId);
  const upz = dist?.upazilas.find((u) => u.id === upazilaId);

  const parts = [];
  if (upz) parts.push(lang === 'bn' ? upz.nameBn : upz.nameEn);
  if (dist) parts.push(lang === 'bn' ? dist.nameBn : dist.nameEn);
  if (div) parts.push(lang === 'bn' ? div.nameBn : div.nameEn);

  return parts.join(', ');
}
